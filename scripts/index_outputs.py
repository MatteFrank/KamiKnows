"""Write docs/outputs_index.md: one table row per run directory under outputs/.

outputs/ is not versioned; this index is. Free-text notes come from
docs/outputs_index_notes.json ({"<run dir>": {"note": "..."}}).

Example:
    python scripts/index_outputs.py
"""

import argparse
import json
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parents[1]))
from kamiknows.common import MANIFEST_NAME, read_json

STEPS = {
    "parse": ("Parsed papers", ["timeout_seconds"], ["papers", "status_counts"]),
    "chunk": ("Chunked datasets", ["chunker", "exclude_backmatter", "target_words", "min_words", "cut_policy"],
              ["chunks"]),
    "retrieve": ("Retrieval runs", ["chunker", "retriever", "embedding_model", "source_policy", "top_k"],
                 ["hit_rate", "mrr"]),
    "generate": ("Generation runs", ["chunker", "retriever", "model", "prompt", "num_predict"], ["answer_status"]),
    "review": ("Manual reviews", [], ["rows", "runs"]),
    "chat": ("Chat sessions", ["retriever", "model"], ["turns"]),
}


def cell(value) -> str:
    if value is None:
        return ""
    return json.dumps(value, ensure_ascii=False) if isinstance(value, (dict, list)) else str(value)


def build_index(outputs_dir: Path, notes: dict) -> str:
    rows: dict[str, list[str]] = {step: [] for step in STEPS}
    unindexed = []
    for run_dir in sorted(p for p in outputs_dir.iterdir() if p.is_dir() and not p.name.startswith("_")):
        manifest_path = run_dir / MANIFEST_NAME
        manifest = read_json(manifest_path) if manifest_path.exists() else {}
        step = manifest.get("step")
        note = notes.get(run_dir.name, {}).get("note", "")
        if step not in STEPS:
            unindexed.append(f"| `{run_dir.name}` | {note} |")
            continue
        _, params, summary = STEPS[step]
        values = [manifest["created_at"][:10]]
        values += [cell(manifest["params"].get(key)) for key in params]
        values += [cell(manifest["summary"].get(key)) for key in summary]
        rows[step].append(f"| `{run_dir.name}` | " + " | ".join(values) + f" | {note} |")

    lines = ["# Outputs index", "",
             "Generated by `python scripts/index_outputs.py`; edit notes in `docs/outputs_index_notes.json`.", ""]
    for step, (title, params, summary) in STEPS.items():
        if not rows[step]:
            continue
        header = ["Directory", "Date", *params, *summary, "Note"]
        lines += [f"## {title}", "", "| " + " | ".join(header) + " |", "|" + "---|" * len(header), *rows[step], ""]
    if unindexed:
        lines += ["## Without a manifest (older layout)", "", "| Directory | Note |", "|---|---|", *unindexed, ""]
    return "\n".join(lines)


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("--outputs-dir", type=Path, default=Path("outputs"),
                        help="directory with the run directories (default: outputs)")
    parser.add_argument("--notes", type=Path, default=Path("docs/outputs_index_notes.json"),
                        help="JSON with a note per run (default: docs/outputs_index_notes.json)")
    parser.add_argument("--output", type=Path, default=Path("docs/outputs_index.md"),
                        help="Markdown file to write (default: docs/outputs_index.md)")
    args = parser.parse_args(argv)
    notes = read_json(args.notes) if args.notes.exists() else {}
    args.output.write_text(build_index(args.outputs_dir, notes), encoding="utf-8")
    print(f"Wrote {args.output}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
